/**
 * PURPOSE
 * -------
 * Runs deterministic safety checks on inbound user messages.
 * This is the FIRST gate in the chat pipeline — it runs BEFORE
 * emotion detection, context retrieval, and response generation.
 *
 * RESPONSIBILITIES
 * -------
 * - Check for crisis keywords and self-harm indicators
 * - Return a structured SafetyResult
 * - Provide a predefined safe crisis response
 *
 * NEVER
 * -------
 * - Generate AI responses
 * - Store messages
 * - Call external services
 *
 * EXPORTS
 * -------
 * safetyService.checkMessage(text) → SafetyResult
 *
 * DEPENDS ON
 * -------
 * shared/logger
 */

import logger from '../../../shared/logger/logger.js';

// ── Crisis keyword patterns ────────────────────────────────────────
// Deterministic keyword matching — no AI required.
// Intentionally conservative: false positives are acceptable;
// false negatives are not.

const CRISIS_PATTERNS = [
  /\bsuicid/i,
  /\bkill\s*(my)?self/i,
  /\bend\s+my\s+life/i,
  /\bwant\s+to\s+die/i,
  /\bself.?harm/i,
  /\bcut\s+myself/i,
  /\bhurt\s+myself/i,
  /\bno\s+reason\s+to\s+live/i,
  /\bcan'?t\s+go\s+on/i,
  /\bgive\s+up\s+on\s+life/i,
  /\boverdose/i,
  /\btake\s+my\s+own\s+life/i,
];

// Predefined safe crisis response — never generated by AI
const CRISIS_RESPONSE_TEXT =
  "I'm really glad you reached out, and I want you to know you're not alone. " +
  "What you're feeling matters deeply. Please consider contacting a crisis " +
  "helpline right now — they have trained counsellors available 24/7. " +
  "In India you can call iCall at 9152987821. International users can visit " +
  "findahelpline.com to locate support in your country. " +
  "If you are in immediate danger, please call emergency services (112 in India, " +
  "911 in the US, 999 in the UK). You deserve care and support.";

// ── Safety statuses ────────────────────────────────────────────────
const STATUS = Object.freeze({
  SAFE:      'safe',
  HIGH_RISK: 'high_risk',
});

class SafetyService {
  /**
   * Check an inbound user message for crisis/high-risk content.
   *
   * @param   {string} text — raw user message text
   * @returns {SafetyResult}
   *
   * @typedef {Object} SafetyResult
   * @property {string}  status        — 'safe' | 'high_risk'
   * @property {boolean} isHighRisk    — true when status is 'high_risk'
   * @property {string|null} crisisResponse — predefined response text or null
   */
  checkMessage(text) {
    if (!text || typeof text !== 'string') {
      return this._safe();
    }

    const isHighRisk = CRISIS_PATTERNS.some((pattern) => pattern.test(text));

    if (isHighRisk) {
      logger.warn('Safety gate: high-risk message detected', {
        // Log that a crisis was detected but NEVER log the message content
        triggered: true,
      });

      return {
        status:        STATUS.HIGH_RISK,
        isHighRisk:    true,
        crisisResponse: CRISIS_RESPONSE_TEXT,
      };
    }

    return this._safe();
  }

  _safe() {
    return {
      status:        STATUS.SAFE,
      isHighRisk:    false,
      crisisResponse: null,
    };
  }
}

export const SAFETY_STATUS = STATUS;
export default new SafetyService();
